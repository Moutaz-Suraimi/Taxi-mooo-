const LanguageContext = createContext<LanguageContextType>({
  language: 'nl',
  setLanguage: () => {},
  toggleLanguage: () => {},
  t: (key: string) => key,
});

export const LanguageProvider: React.FC<{ children: React.ReactNode }> = ({ children }) => {
  const [language, setLanguageState] = useState<Language>(() => {
    try {
      const saved = localStorage.getItem('taximooo_lang') as Language;
      if (saved && ['nl', 'en', 'ar', 'es'].includes(saved)) {
        if (typeof document !== 'undefined') {
          document.documentElement.lang = saved;
          document.documentElement.dir = saved === 'ar' ? 'rtl' : 'ltr';
        }
        return saved;
      }
      return 'nl';
    } catch {
      return 'nl';
    }
  });

  const setLanguage = (lang: Language) => {
    setLanguageState(lang);
    try {
      localStorage.setItem('taximooo_lang', lang);
      if (typeof document !== 'undefined') {
        document.documentElement.lang = lang;
        document.documentElement.dir = lang === 'ar' ? 'rtl' : 'ltr';
      }
    } catch {}
  };

  const toggleLanguage = () => {
    const list: Language[] = ['nl', 'en', 'ar', 'es'];
    const nextIdx = (list.indexOf(language) + 1) % list.length;
    setLanguage(list[nextIdx]);
  };

  const t = (key: string): string => {
    return translations[language]?.[key] || translations['nl']?.[key] || key;
  };

  return (
    <LanguageContext.Provider value={{ language, setLanguage, toggleLanguage, t }}>
      {children}
    </LanguageContext.Provider>
  );
};

export const useLanguage = () => useContext(LanguageContext);
